#!/usr/bin/env node
// Verifies that every installed dependency carries a licence compatible with
// distributing this project under MIT, and (with --write) regenerates the
// inventory in docs/licenses/THIRD_PARTY_LICENSES.md.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(readFileSync(path.join(root, 'package-lock.json'), 'utf8'));

// Permissive licences, plus weak-copyleft ones that only bind changes to the
// dependency's own files (acceptable for an unmodified dependency).
const ALLOWED = new Set([
  'MIT', 'MIT-0', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0', 'BlueOak-1.0.0', 'CC0-1.0', 'Unlicense',
  'Python-2.0', 'Zlib', 'WTFPL', 'MPL-2.0',
  // Data/documentation licences that reach us only through build tooling.
  'CC-BY-4.0', 'CC-BY-3.0',
]);

// A package whose manifest states its licence in a non-standard way, verified by hand.
const REVIEWED = {};

function normalise(licence) {
  if (!licence) return null;
  if (typeof licence === 'object') return normalise(licence.type ?? licence.name);
  return String(licence).trim();
}

/** Accepts SPDX expressions: "A OR B" needs one allowed side, "A AND B" needs both. */
function isAllowed(expression) {
  const text = expression.replace(/^\(|\)$/g, '').trim();
  if (text.includes(' OR ')) return text.split(' OR ').some((part) => isAllowed(part));
  if (text.includes(' AND ')) return text.split(' AND ').every((part) => isAllowed(part));
  return ALLOWED.has(text);
}

const rows = [];
const problems = [];
for (const [location, entry] of Object.entries(lock.packages)) {
  if (location === '' || entry.link || !location.includes('node_modules/')) continue;
  const name = location.slice(location.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const manifestPath = path.join(root, location, 'package.json');
  if (!existsSync(manifestPath)) {
    if (entry.optional) continue; // an optional platform package not installed on this machine
    problems.push(`${name}@${entry.version}: not installed (run npm ci)`);
    continue;
  }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const licence = REVIEWED[`${name}@${manifest.version}`] ?? normalise(manifest.license ?? manifest.licenses?.[0]) ?? normalise(entry.license);
  const scope = entry.dev ? 'development' : 'runtime';
  if (!licence) problems.push(`${name}@${manifest.version}: no licence declared`);
  else if (!isAllowed(licence)) problems.push(`${name}@${manifest.version}: "${licence}" is not on the allow-list`);
  rows.push({ name, version: manifest.version, licence: licence ?? 'UNKNOWN', scope });
}

rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const unique = rows.filter((row, index) => index === 0 || row.name !== rows[index - 1].name || row.version !== rows[index - 1].version);
const count = (scope) => unique.filter((row) => row.scope === scope).length;
const byLicence = {};
for (const row of unique) byLicence[row.licence] = (byLicence[row.licence] ?? 0) + 1;

if (process.argv.includes('--write')) {
  const lines = [
    '# Third-party licences',
    '',
    'Generated by `node scripts/check-licenses.mjs --write` from `package-lock.json`. Do not edit by hand.',
    '',
    `${unique.length} packages: ${count('runtime')} are installed with the application, ${count('development')} are used only to build and test it.`,
    '',
    '| Licence | Packages |',
    '|---|---|',
    ...Object.entries(byLicence).sort((a, b) => b[1] - a[1]).map(([licence, n]) => `| ${licence} | ${n} |`),
    '',
    '## Runtime dependencies',
    '',
    '| Package | Version | Licence |',
    '|---|---|---|',
    ...unique.filter((row) => row.scope === 'runtime').map((row) => `| ${row.name} | ${row.version} | ${row.licence} |`),
    '',
    '## Development dependencies',
    '',
    '| Package | Version | Licence |',
    '|---|---|---|',
    ...unique.filter((row) => row.scope === 'development').map((row) => `| ${row.name} | ${row.version} | ${row.licence} |`),
    '',
  ];
  writeFileSync(path.join(root, 'docs/licenses/THIRD_PARTY_LICENSES.md'), lines.join('\n'));
}

console.log(`${unique.length} packages (${count('runtime')} runtime, ${count('development')} development)`);
for (const [licence, n] of Object.entries(byLicence).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(4)}  ${licence}`);
if (problems.length > 0) {
  console.error('\nLicence problems:');
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}
console.log('\nAll licences are on the allow-list.');
