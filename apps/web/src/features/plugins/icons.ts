/**
 * The icons a plugin may name. A plugin never supplies an image to the
 * Studio's page: it picks a name from this set, and a name the client does
 * not know falls back to a puzzle piece (a link for link tiles).
 */
const PLUGIN_ICONS: Record<string, LucideIcon> = {
  activity: Activity,
  bell: Bell,
  book: BookOpen,
  bot: Bot,
  calendar: Calendar,
  chart: ChartLine,
  'bar-chart': BarChart3,
  check: CheckSquare,
  clock: Clock,
  cloud: Cloud,
  code: Code,
  compass: Compass,
  dashboard: LayoutDashboard,
  database: Database,
  'external-link': ExternalLink,
  file: FileText,
  flag: Flag,
  folder: Folder,
  gauge: Gauge,
  github: Code,
  globe: Globe,
  heart: Heart,
  inbox: Inbox,
  key: KeyRound,
  lightbulb: Lightbulb,
  link: Link,
  list: List,
  mail: Mail,
  map: MapIcon,
  message: MessageSquare,
  notebook: Notebook,
  package: Package,
  palette: Palette,
  pen: PenTool,
  puzzle: Puzzle,
  rocket: Rocket,
  search: Search,
  server: Server,
  settings: Settings,
  shield: Shield,
  cart: ShoppingCart,
  sparkles: Sparkles,
  star: Star,
  tag: Tag,
  terminal: Terminal,
  timer: Timer,
  users: Users,
  wrench: Wrench,
  zap: Zap,
};

export function pluginIcon(name: string, fallback: 'panel' | 'link' = 'panel'): LucideIcon {
  return PLUGIN_ICONS[name] ?? (fallback === 'link' ? Link : Puzzle);
}
