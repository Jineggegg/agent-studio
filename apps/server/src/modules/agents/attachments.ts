/**
 * Files attached to messages.
 *
 * They are stored inside the data directory, one folder per session, under
 * generated names — a client never chooses where a file lands or what it is
 * called on disk. They are served back only to people who can see the
 * session, as downloads unless they are verified raster images, and never
 * with a type a browser would execute.
 *
 * Note for adapter authors: the sandbox hides the data directory from agent
 * processes, and these files live in it. An adapter receives each file's
 * absolute path in `request.prompt.attachments[].path` and must pass those
 * paths through `SandboxProfile.expose` for the agent to be able to read them.
 */

/** Unsent files one session may hold, so uploads cannot fill the disk unnoticed. */
const MAX_PENDING_PER_SESSION = 40;
const STORED_NAME = /^[0-9a-z]{26}(\.[a-z0-9]{1,10})?$/;
const SESSION_DIR = /^[0-9a-z]{26}$/;

/** What the first bytes of each raster format look like. A declared image type is believed only when they match. */
function looksLike(mediaType: string, head: Buffer): boolean {
  switch (mediaType) {
    case 'image/png':
      return head.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]));
    case 'image/jpeg':
      return head[0] === 0xff && head[1] === 0xd8 && head[2] === 0xff;
    case 'image/gif':
      return ['GIF87a', 'GIF89a'].includes(head.subarray(0, 6).toString('latin1'));
    case 'image/webp':
      return head.subarray(0, 4).toString('latin1') === 'RIFF' && head.subarray(8, 12).toString('latin1') === 'WEBP';
    default:
      return false;
  }
}

function displayName(raw: string | undefined): string {
  const base = (raw ?? '').split(/[\\/]/).pop() ?? '';
  // eslint-disable-next-line no-control-regex
  const cleaned = base.replace(/[\u0000-\u001f\u007f]/g, '').trim();
  return cleaned === '' || cleaned === '.' || cleaned === '..' ? 'file' : [...cleaned].slice(0, 200).join('');
}

function declaredType(raw: string | undefined): string {
  const value = (raw ?? '').toLowerCase().split(';')[0]!.trim();
  return /^[a-z0-9][a-z0-9.+-]{0,60}\/[a-z0-9][a-z0-9.+-]{0,60}$/.test(value) ? value : 'application/octet-stream';
}

export class AttachmentFiles {
  readonly #root: string;
  readonly #store: AgentStore;
  readonly #sessions: SessionService;

  constructor(deps: { dataDir: string; store: AgentStore; sessions: SessionService }) {
    this.#root = path.join(deps.dataDir, 'attachments');
    this.#store = deps.store;
    this.#sessions = deps.sessions;
  }

  /** Absolute path of a stored file. Both parts are generated by the server and checked again here. */
  pathOf(row: AttachmentRow): string {
    if (!SESSION_DIR.test(row.session_id) || !STORED_NAME.test(row.stored_name)) throw new Error('Not a stored attachment.');
    return path.join(this.#root, row.session_id, row.stored_name);
  }

  async removeSession(sessionId: string): Promise<void> {
    if (!SESSION_DIR.test(sessionId)) return;
    await rm(path.join(this.#root, sessionId), { recursive: true, force: true });
  }

  /** Removes folders whose session no longer exists (an account or a project was deleted). */
  async sweep(existing: ReadonlySet<string>): Promise<void> {
    const entries = await readdir(this.#root).catch(() => [] as string[]);
    for (const entry of entries) {
      if (SESSION_DIR.test(entry) && !existing.has(entry)) await this.removeSession(entry);
    }
  }

  list(principal: Principal, sessionId: string, pendingOnly: boolean): Attachment[] {
    this.#sessions.requireSession(principal, sessionId, 'view');
    return this.#store.attachmentsOfSession(sessionId, pendingOnly).map(presentAttachment);
  }

  async remove(principal: Principal, sessionId: string, attachmentId: string): Promise<void> {
    this.#sessions.requireSession(principal, sessionId, 'write');
    const row = this.#store.attachment(sessionId, attachmentId);
    if (!row) throw notFound('No such attachment.', 'attachment_not_found');
    if (row.sent_at !== null) throw conflict('That attachment has already been sent with a message.', 'attachment_already_sent');
    this.#store.deleteAttachment(sessionId, attachmentId);
    await unlink(this.pathOf(row)).catch(() => {});
  }

  /**
   * Gives another session its own copies of files the caller uploaded and has
   * not sent yet, so one upload can go out with messages in several sessions.
   * The originals stay where they are, unsent. Both ends are the caller's own:
   * a file of somebody else's session answers exactly like one that does not
   * exist. Returns the copies, in the order asked for.
   */
  async copyTo(principal: Principal, attachmentIds: readonly string[], targetSessionId: string): Promise<Attachment[]> {
    this.#sessions.requireSession(principal, targetSessionId, 'write');
    const missing = () => unprocessable('An attachment of this message was not found.', 'attachment_not_found');
    const sources: AttachmentRow[] = [];
    for (const id of new Set(attachmentIds)) {
      const row = this.#store.attachmentById(id);
      if (!row || row.user_id !== principal.userId) throw missing();
      try {
        this.#sessions.requireSession(principal, row.session_id, 'write');
      } catch {
        throw missing();
      }
      if (row.sent_at !== null) throw unprocessable('An attachment of this message was already sent.', 'attachment_already_sent');
      sources.push(row);
    }
    if (sources.length > AGENT_LIMITS.attachmentsPerMessage) {
      throw unprocessable(`A message can carry at most ${AGENT_LIMITS.attachmentsPerMessage} files.`, 'too_many_attachments');
    }
    if (this.#store.attachmentsOfSession(targetSessionId, true).length + sources.length > MAX_PENDING_PER_SESSION) {
      throw unprocessable('Too many unsent files are waiting in that session.', 'too_many_attachments');
    }
    const directory = path.join(this.#root, targetSessionId);
    await mkdir(directory, { recursive: true, mode: 0o700 });
    const copies: AttachmentRow[] = [];
    // Lists show a session's files in the order they arrived: the copies keep the order they were asked for in.
    const now = Date.now();
    try {
      for (const [index, source] of sources.entries()) {
        const id = newId();
        const extension = /\.([a-z0-9]{1,10})$/.exec(source.stored_name)?.[1];
        const copy: AttachmentRow = { ...source, id, session_id: targetSessionId, stored_name: extension ? `${id}.${extension}` : id, sent_at: null, created_at: now + index };
        copies.push(copy);
        await copyFile(this.pathOf(source), this.pathOf(copy), constants.COPYFILE_EXCL);
        this.#store.insertAttachment(copy);
      }
    } catch (error) {
      // Nothing half-copied is left behind: neither a row nor a file.
      for (const copy of copies) {
        this.#store.deleteAttachment(targetSessionId, copy.id);
        await unlink(this.pathOf(copy)).catch(() => {});
      }
      if (error instanceof StudioError) throw error;
      throw unprocessable('An attachment of this message could not be read.', 'attachment_not_found');
    }
    return copies.map(presentAttachment);
  }

  /** Stores the files of one multipart request. Files over a limit are refused one by one; the rest are kept. */
  async upload(principal: Principal, sessionId: string, request: FastifyRequest): Promise<UploadAttachmentsResponse> {
    this.#sessions.requireSession(principal, sessionId, 'write');
    if (typeof request.isMultipart !== 'function' || !request.isMultipart()) {
      throw badRequest('Send the files as multipart/form-data.', undefined, 'not_multipart');
    }
    const declaredLength = Number(request.headers['content-length'] ?? 0);
    if (declaredLength > AGENT_LIMITS.attachmentsPerMessage * AGENT_LIMITS.attachmentBytes + 1024 * 1024) {
      throw payloadTooLarge('That upload is too large.', 'upload_too_large');
    }
    const directory = path.join(this.#root, sessionId);
    await mkdir(directory, { recursive: true, mode: 0o700 });

    const accepted: AttachmentRow[] = [];
    const rejected: RejectedAttachment[] = [];
    let pending = this.#store.attachmentsOfSession(sessionId, true).length;
    const megabytes = Math.round(AGENT_LIMITS.attachmentBytes / (1024 * 1024));

    const options = {
      limits: { fileSize: AGENT_LIMITS.attachmentBytes, files: 64, fields: 16, fieldSize: 4096, parts: 96 },
      // A file over the limit is refused by itself; it must not abort the files that follow it.
      throwFileSizeLimit: false,
    };
    try {
      for await (const part of request.parts(options as Parameters<FastifyRequest['parts']>[0])) {
        if (part.type !== 'file') continue;
        const name = displayName(part.filename);
        if (accepted.length >= AGENT_LIMITS.attachmentsPerMessage) {
          part.file.resume();
          rejected.push({ name, code: 'too_many_attachments', message: `A message can carry at most ${AGENT_LIMITS.attachmentsPerMessage} files.` });
          continue;
        }
        if (pending >= MAX_PENDING_PER_SESSION) {
          part.file.resume();
          rejected.push({ name, code: 'too_many_attachments', message: 'Too many unsent files are waiting in this session. Send or remove some first.' });
          continue;
        }
        const id = newId();
        const extension = /\.([A-Za-z0-9]{1,10})$/.exec(name)?.[1]?.toLowerCase();
        const storedName = extension ? `${id}.${extension}` : id;
        const target = path.join(directory, storedName);
        await pipeline(part.file, createWriteStream(target, { mode: 0o600, flags: 'wx' }));
        if (part.file.truncated) {
          await unlink(target).catch(() => {});
          rejected.push({ name, code: 'attachment_too_large', message: `"${name}" is larger than ${megabytes} MB.` });
          continue;
        }
        const size = (await stat(target)).size;
        if (size === 0) {
          await unlink(target).catch(() => {});
          rejected.push({ name, code: 'attachment_empty', message: `"${name}" is empty.` });
          continue;
        }
        let mediaType = declaredType(part.mimetype);
        if (RASTER_IMAGE_TYPES.has(mediaType)) {
          const handle = await open(target, 'r');
          try {
            const head = Buffer.alloc(16);
            await handle.read(head, 0, 16, 0);
            if (!looksLike(mediaType, head)) mediaType = 'application/octet-stream';
          } finally {
            await handle.close();
          }
        }
        const row: AttachmentRow = {
          id,
          session_id: sessionId,
          user_id: principal.userId,
          name,
          stored_name: storedName,
          media_type: mediaType,
          size,
          sent_at: null,
          created_at: Date.now(),
        };
        this.#store.insertAttachment(row);
        accepted.push(row);
        pending += 1;
      }
    } catch (error) {
      // A broken upload leaves nothing half-stored behind.
      for (const row of accepted) {
        this.#store.deleteAttachment(sessionId, row.id);
        await unlink(this.pathOf(row)).catch(() => {});
      }
      if (error instanceof StudioError) throw error;
      const status = (error as { statusCode?: number }).statusCode;
      if (status === 413) throw payloadTooLarge('That upload has too many parts.', 'upload_too_large');
      request.log.warn({ err: describeError(error) }, 'an attachment upload could not be read');
      throw badRequest('The upload could not be read.', undefined, 'invalid_upload');
    }

    if (accepted.length === 0) {
      const first = rejected[0];
      if (!first) throw badRequest('The upload contains no file.', undefined, 'no_files');
      if (first.code === 'attachment_too_large') throw new StudioError(413, first.code, first.message, { rejected });
      throw new StudioError(400, first.code, first.message, { rejected });
    }
    return { attachments: accepted.map(presentAttachment), rejected };
  }

  /** Sends a stored file back with headers that keep a browser from treating it as anything but data. */
  async serve(principal: Principal, sessionId: string, attachmentId: string, reply: FastifyReply): Promise<unknown> {
    this.#sessions.requireSession(principal, sessionId, 'view');
    const row = this.#store.attachment(sessionId, attachmentId);
    if (!row) throw notFound('No such attachment.', 'attachment_not_found');
    const file = this.pathOf(row);
    const info = await stat(file).catch(() => null);
    if (!info?.isFile()) throw notFound('No such attachment.', 'attachment_not_found');
    const inline = RASTER_IMAGE_TYPES.has(row.media_type);
    const fallback = row.name.replace(/[^\x20-\x7e]/g, '_').replace(/["\\]/g, '_');
    void reply
      .header('content-type', inline ? row.media_type : 'application/octet-stream')
      .header('content-length', String(info.size))
      .header('content-disposition', `${inline ? 'inline' : 'attachment'}; filename="${fallback}"; filename*=UTF-8''${encodeURIComponent(row.name)}`)
      .header('x-content-type-options', 'nosniff')
      .header('content-security-policy', "default-src 'none'; sandbox")
      .header('cache-control', 'private, no-store');
    return createReadStream(file);
  }
}

const sessionParams = z.object({ sessionId: idSchema });
const attachmentParams = z.object({ sessionId: idSchema, attachmentId: idSchema });
const listQuery = z.object({ pending: z.enum(['true', 'false']).default('true') });

export async function registerAttachmentRoutes(context: ModuleContext, files: AttachmentFiles): Promise<void> {
  const { http } = context;

  // Multipart parsing is enabled for this one route only, inside its own scope, so no other
  // module's choice of body parser is affected by it (or affects it).
  await http.app.register(async (scope) => {
    if (!scope.hasContentTypeParser('multipart/form-data')) {
      await scope.register(multipart, { limits: { fileSize: AGENT_LIMITS.attachmentBytes }, throwFileSizeLimit: false });
    }
    const studio: RouteConfig = { access: 'user', scope: 'write', sessionOnly: false, recentAuth: false };
    scope.route({
      method: 'POST',
      url: '/api/sessions/:sessionId/attachments',
      config: { studio },
      handler: async (request, reply) => {
        if (!request.principal) throw unauthorized();
        const params = sessionParams.parse(request.params ?? {});
        const result = await files.upload(request.principal, params.sessionId, request);
        return reply.status(201).send(result);
      },
    });
  });

  http.route({
    method: 'GET',
    url: '/api/sessions/:sessionId/attachments',
    access: 'user',
    params: sessionParams,
    query: listQuery,
    handler: ({ user, params, query }) => ({ attachments: files.list(user, params.sessionId, query.pending === 'true') }),
  });

  http.route({
    method: 'GET',
    url: '/api/sessions/:sessionId/attachments/:attachmentId',
    access: 'user',
    params: attachmentParams,
    handler: ({ user, params, reply }) => files.serve(user, params.sessionId, params.attachmentId, reply),
  });

  http.route({
    method: 'DELETE',
    url: '/api/sessions/:sessionId/attachments/:attachmentId',
    access: 'user',
    params: attachmentParams,
    handler: ({ user, params }) => files.remove(user, params.sessionId, params.attachmentId),
  });
}
